function df_sports(array $content,bool $includeDisabled=false): array {
    $sports=$content['sports']??[];
    if(!$includeDisabled)$sports=array_values(array_filter($sports,fn($s)=>!empty($s['enabled'])));
    usort($sports,fn($a,$b)=>((int)($a['order']??999))<=>((int)($b['order']??999)));
    return $sports;
}
function df_find_sport(array $content,string $slug): ?array {
    foreach($content['sports']??[] as $s) if(($s['slug']??'')===$slug)return $s;
    return null;
}
function df_affiliate_url(array $content,string $slug='all-sports'): string {
    if($slug==='all-sports') return trim((string)($content['general']['home_affiliate_url']??'#'))?:'#';
    $s=df_find_sport($content,$slug);
    $url=trim((string)($s['affiliate_url']??''));
    return $url!==''?$url:(trim((string)($content['general']['home_affiliate_url']??'#'))?:'#');
}
function df_watch_label(array $content,?array $sport=null): string {
    $label=$sport?trim((string)($sport['primary_button']??'')):trim((string)($content['general']['home_primary_button']??'Watch Live Now'));
    if($label==='')$label=$sport?'Watch '.($sport['name']??'Sports').' Live Now':'Watch Live Now';
    if(!empty($content['general']['use_free_wording'])&&stripos($label,'free')===false)$label.=' Free';
    return $label;
}
function df_media_url(string $url): string {
    $url=trim($url);
    if($url==='')return '';
    if(preg_match('#^https?://#i',$url)||str_starts_with($url,'/'))return $url;
    global $BASE_PATH;
    return rtrim($BASE_PATH,'/').'/'.ltrim($url,'/');
}


function df_menu_sports(array $content): array {
    $sports=df_sports($content);
    return array_values(array_filter($sports,fn($s)=>!array_key_exists('menu_enabled',$s)||!empty($s['menu_enabled'])));
}

function df_slugify_sport(string $value): string {
    $value=strtolower(trim($value));
    $value=preg_replace('/[^a-z0-9]+/','-',$value)??'';
    return trim($value,'-');
}

